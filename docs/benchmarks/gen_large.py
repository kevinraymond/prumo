#!/usr/bin/env python3
"""Write docs/large/main.tex: a book of a few thousand pages for the scale test.

Deterministic: the same arguments give the same file. Text comes from lipsum, so the
source stays small; every section has an equation and a cross-reference, every fifth a
table, every chapter a TikZ picture. Same source on all three engines.

Usage: gen_large.py [--chapters 140] [--sections 20] [--out docs/large/main.tex]
"""
import argparse
import pathlib

HEAD = r"""% Generated by gen_large.py (CHAPTERS chapters x SECTIONS sections). Do not edit.
\documentclass{book}
\usepackage{iftex}
\ifPDFTeX
  \usepackage[T1]{fontenc}
  \usepackage{lmodern}
\else
  \usepackage{fontspec}
\fi
\usepackage{amsmath}
\usepackage{booktabs}
\usepackage{tikz}
\usepackage{lipsum}
\usepackage{microtype}
\usepackage{hyperref}
\begin{document}
\frontmatter
\title{A Large Book}
\author{gen\_large.py}
\date{9 November 2026}
\maketitle
\tableofcontents
\mainmatter
"""

TABLE = r"""
\begin{table}[htbp]
  \centering
  \begin{tabular}{lrr}
    \toprule
    item & value & share \\
    \midrule
    alpha & %d & 0.%02d \\
    beta & %d & 0.%02d \\
    gamma & %d & 0.%02d \\
    \bottomrule
  \end{tabular}
  \caption{Table %d.%d.}\label{tab:%d-%d}
\end{table}
"""

PICTURE = r"""
\begin{figure}[htbp]
  \centering
  \begin{tikzpicture}
    \foreach \i in {1,...,%d} { \draw (\i*0.4,0) circle (0.15); }
    \draw[->] (0,-0.5) -- (%d*0.4+0.4,-0.5);
  \end{tikzpicture}
  \caption{Picture %d.}\label{fig:%d}
\end{figure}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--chapters", type=int, default=140)
    ap.add_argument("--sections", type=int, default=20)
    ap.add_argument("--out", default=str(pathlib.Path(__file__).parent / "docs/large/main.tex"))
    a = ap.parse_args()
    out = [HEAD.replace("CHAPTERS", str(a.chapters)).replace("SECTIONS", str(a.sections))]
    n = 0
    for c in range(1, a.chapters + 1):
        out.append(f"\\chapter{{Chapter {c}}}\\label{{ch:{c}}}\n")
        out.append(PICTURE % (3 + c % 8, 3 + c % 8, c, c))
        for s in range(1, a.sections + 1):
            n += 1
            first = (n * 7) % 145 + 1
            out.append(f"\\section{{Section {c}.{s}}}\\label{{sec:{c}-{s}}}\n")
            out.append(f"\\lipsum[{first}-{first + 5}]\n")
            out.append(
                f"\\begin{{equation}}\\label{{eq:{c}-{s}}}\n"
                f"  \\sum_{{k=1}}^{{{n}}} \\frac{{1}}{{k^2}} \\le \\frac{{\\pi^2}}{{6}}, \\qquad x_{{{c}}} = {s}.\n"
                f"\\end{{equation}}\n"
            )
            prev = f"sec:{c}-{s - 1}" if s > 1 else f"ch:{c}"
            out.append(f"As in \\ref{{{prev}}} on page~\\pageref{{{prev}}}, and see figure~\\ref{{fig:{c}}}.\n\n")
            if s % 5 == 0:
                out.append(TABLE % (n, n % 100, n * 2, (n * 3) % 100, n * 3, (n * 7) % 100, c, s, c, s))
    out.append("\\end{document}\n")
    p = pathlib.Path(a.out)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("".join(out))
    print(f"{p}: {a.chapters} chapters, {n} sections, {p.stat().st_size} bytes")


if __name__ == "__main__":
    main()
